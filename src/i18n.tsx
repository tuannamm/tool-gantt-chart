export const STRINGS = { en, vi }
export type Lang = keyof typeof STRINGS

const KEY = 'gantt-lang'

// English by default; the choice is remembered per browser and mirrored to <html lang>.
export function useLang() {
  const [lang, setLang] = useState<Lang>(() => {
    try { return localStorage.getItem(KEY) === 'vi' ? 'vi' : 'en' } catch { return 'en' }
  })
  useEffect(() => {
    document.documentElement.lang = lang
    try { localStorage.setItem(KEY, lang) } catch { /* storage blocked */ }
  }, [lang])
  return [lang, setLang] as const
}

export const I18n = createContext<Strings>(en)
export const useT = () => useContext(I18n)
